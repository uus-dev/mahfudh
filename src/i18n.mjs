// Strings the browser script needs (functions are serialized as templates with {0},{1},{2}).
export function clientStrings(lang) {
  const out = {};
  for (const [k, v] of Object.entries(UI[lang])) out[k] = typeof v === 'function' ? v('{0}', '{1}', '{2}') : v;
  return out;
}

